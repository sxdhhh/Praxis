package dev.praxis.core.tool

/**
 * 工具调用失败的位置。
 *
 * ## 为什么必须区分这五类（2026-11-06）
 *
 * 旧实现把所有失败都压成 `isError = true` 的一句字符串。后果是模型
 * **无法判断「能不能重试」**：
 *
 *  - 参数错了 → 改参数重试，安全；
 *  - 已经执行了一半 → 重试可能把写了一半的文件再写一遍。
 *
 * 这两者对模型下一步的决策**完全相反**。混在一起的代价是：
 * 模型要么不敢重试（卡住），要么盲目重试（数据被改两次）。
 *
 * ## 五类的判据与恢复方式（照 Harness `tools` 篇）
 *
 * | 位置 | 业务副作用可能发生吗 | 恢复方式 |
 * |---|---|---|
 * | [Argument] | **否**（尚未进入 execute） | 修参数后重调 |
 * | [Denied] | **否** | 换方案或请求提权；**不要**把拒绝改判成允许 |
 * | [Execution] | **可能已部分执行** | 查实际状态，按幂等/补偿恢复 |
 * | [Output] | **可能已完成** | 先确认副作用再考虑重试 |
 * | [Rendering] | **无法判断** | 查最终结果，**不从界面外观推断** |
 *
 * 最后一类尤其容易被忽略：工具卡显示不全 **不等于** 执行失败。
 */
enum class ToolFailureStage {
    /** 参数不合法（JSON 解析失败 / 缺必填）。副作用必然未发生。 */
    Argument,

    /** 权限拒绝（含用户拒绝）。副作用必然未发生。 */
    Denied,

    /** 执行中抛错或取消。**可能已部分执行**。 */
    Execution,

    /** 执行完成但返回值不合法。**可能已完成**。 */
    Output,

    /** 呈现层失败（工具卡渲染异常）。**无法判断**执行状态。 */
    Rendering,
    ;

    /**
     * 该位置的失败是否可以安全重试。
     *
     * ## 为什么只有前两类是 `true`
     *
     * 重试的本质是「再执行一次」。只有在**确定上一次没有产生任何效果**时，
     * 再执行一次才等价于「第一次执行」。
     *
     * [Execution] 与 [Output] 都可能已经写了一半，盲目重试会让副作用翻倍
     * （比如 `append_file` 追加两遍）。它们需要先查状态再决定 —— 那是一个
     * 需要模型判断的步骤，不能由框架代为决定。
     */
    val safeToRetry: Boolean
        get() = this == Argument || this == Denied

    /**
     * 给模型的恢复建议。
     *
     * ## 为什么要显式写给模型看
     *
     * 模型看到 `isError = true` 时的默认反应是「换个写法再试一次」。
     * 对 [Execution] 来说那正是最危险的做法。所以要在结果文本里
     * **直接说明该怎么做**，而不是指望模型自己推断。
     */
    val recoveryHint: String
        get() = when (this) {
            Argument -> "参数有误，修正后可以重试。"
            Denied -> "权限不足，请换一种方案，或请用户提升权限档位。不要假设已获得授权。"
            Execution -> "执行过程中出错，**可能已产生部分效果**。重试前请先用读取类工具确认实际状态。"
            Output -> "执行已完成但返回数据异常。**副作用可能已经发生**，确认后再决定是否重试。"
            Rendering -> "界面呈现失败，不代表执行失败。请以工具返回的最终结果为准。"
        }
}
