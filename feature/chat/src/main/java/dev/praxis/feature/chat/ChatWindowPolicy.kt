package dev.praxis.feature.chat

/**
 * 长对话的渲染预算。
 *
 * ## 上一版为什么被删掉（2026-10-22，真机自查）
 *
 * 上一版实现的是「视口 ± N 条内渲染真实内容，窗口外渲染 96dp 占位」。
 * 这个设计有两个**硬缺陷**，而且方向都错了：
 *
 * 1. **窗口外/内的高度不等** —— 窗口内是真实内容（一条长回答可达 300dp+），
 *    窗口外是固定 96dp。条目跨过窗口边界的瞬间，那条的测量高度从 96dp
 *    突变到 300dp，**列表总高度跟着变**，滚动位置剧烈跳动。
 *    用户手指还在屏幕上、内容却已移走 —— 这比「卡」更难受，
 *    而且它恰好在「滚动」时发生，正是最不该抖的时刻。
 *
 * 2. **它解决的问题 LazyColumn 本来就做了** —— `LazyColumn` 只组合
 *    视口内的条目 + 极少量预取，屏外条目**根本没进 composition**。
 *    再加一层窗口判定，只是把「已经不该渲染的东西」又替换成一次占位测量，
 *    净收益为负。
 *
 * 所以这一层被**整体删除**，`ChatScreen` 回到纯 `LazyColumn`。
 *
 * ## 长对话真正的瓶颈在哪（这是本文件存在的理由）
 *
 * 真机上「长对话卡」的来源不是列表条目数，而是三条**随对话变长而恶化**的量：
 *
 * 1. **每收到一个 delta 就把整个气泡列表 map 一遍**
 *    （`updateBubble` 里 `bubbles.map { ... }`）。列表越长单次 map 越贵，
 *    而流式时一秒几十个 delta，等于每秒几十次与消息总量成正比的分配。
 *    → 已改成「只替换命中项，其余复用原对象」。
 *
 * 2. **Markdown 解析在主线程、随文本长度线性增长**。
 *    一条 8000 字的回答被切成约 800 个 delta，每个 delta 都以全文为 key
 *    重新解析一次 → O(n²) 字符扫描。这才是「长回答越写越卡」的真因。
 *    → 已加解析缓存（只缓存**已完成**的长消息，见 [MarkdownParseCachePolicy]）。
 *
 * 3. **进会话时一次性载入全部历史**。
 *    → 已给恢复加窗口上限（最近 [HISTORY_WINDOW] 条）。
 *
 * 这三条才是用户感受到的「越聊越卡」。
 */
internal object ChatRenderBudget {

    /**
     * 进会话时最多恢复多少条历史。
     *
     * ## 为什么必须有上限
     *
     * 不设上限时，一个聊了几百轮的会话会一次性把几百条消息 map 成气泡，
     * 再把整个列表一次性下发给 UI —— 首帧就要测量几百个条目。
     * 表现是「点进旧会话会白屏几秒」，而且越老的会话越慢。
     *
     * ## 取 200 的理由
     *
     * 正常对话一轮 2 条，200 条约 100 轮。再往上用户的真实需求是
     * 「翻旧账」，那该走搜索/翻页，而不是开局全量载入。
     *
     * ## 只限制 UI，不删数据
     *
     * 数据库里的记录一条都不动 —— 会话列表里看到的仍是完整会话内容与时间。
     * 这里只决定「进页面时先展示最近多少条」。
     */
    const val HISTORY_WINDOW: Int = 200
}

/**
 * Markdown 解析缓存策略。
 *
 * ## 为什么需要
 *
 * `MarkdownParser.parse` 是纯文本扫描，成本与长度线性相关。
 * `MarkdownText` 用 `remember(text)` 缓存结果，但**流式输出时 key 每次都变**
 * （full text 每帧都不同），于是每个 delta 都要重新解析全文：
 *
 * ```
 * 8000 字的回答 ÷ ~10 字/delta ≈ 800 次解析
 * 平均每次扫 4000 字 → 约 320 万字符，且全部在主线程的组合阶段
 * ```
 *
 * 长回答「越写越卡」正是这么来的。
 *
 * ## 为什么缓存只服务「已完成的长消息」
 *
 * 已完成消息的文本**不再变**，但它会被反复重组：滚动回来看、
 * 输入框聚焦/失焦、队列面板展开收起、长按菜单开关 —— 每次都会
 * 重新走组合。此时 `remember(text)` 在**同一个 composition 内**有效，
 * 但条目被滚出视口后组合被销毁、滚回来时重新组合，缓存就没了。
 *
 * 所以需要一个跨组合的缓存。而流式中间态**不该进缓存**：
 * 每个 delta 的文本都不同，写进去只会把 LRU 冲干净，
 * 反而挤掉那些真正会复用的已完成消息。
 */
internal object MarkdownParseCachePolicy {

    /**
     * 短于这个长度就直接解析，不查也不写缓存。
     *
     * 512 字符的解析成本 ≈ 微秒级，走缓存（哈希 key + LRU 操作）
     * 与直接解析差不多贵，还白占一个槽位。
     */
    const val SHORT_TEXT_LIMIT: Int = 512

    /**
     * 缓存多少条。
     *
     * 一条 8000 字回答的块列表约几十个对象，16 条约几十 KB 量级。
     * 再多就是拿内存换一点 CPU，而缓存未命中的代价只是重新解析一次
     * —— 反过来说，缓存占太多内存会挤掉图片/纹理，那才是真卡顿。
     */
    const val MAX_ENTRIES: Int = 16
}